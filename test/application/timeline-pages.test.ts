import assert from "node:assert/strict";
import test from "node:test";
import { DatabaseSync } from "node:sqlite";
import { performance } from "node:perf_hooks";
import { CoordinationApplication } from "../../src/application/coordination-application.ts";
import { createHandoffFixture } from "../support/handoff-fixture.ts";

test("task detail hydrates only fifty newest records and retains independently pinned guidance", async (t) => {
  const fixture = await createHandoffFixture();
  const app = await CoordinationApplication.start({ processDefinitionPath: fixture.definitionPath, databasePath: fixture.databasePath });
  t.after(() => app.close());
  const created = app.createTask({ boardId: "delivery", columnId: "implementation", title: "Large timeline", description: "Whole messages", actor: { kind: "user", id: "paul" }, idempotencyKey: "timeline" });
  assert.ok(created.accepted, JSON.stringify(app.queryStartup()));
  const seed = new DatabaseSync(fixture.databasePath);
  t.after(() => seed.close());
  const insert = seed.prepare("INSERT INTO task_comments(id, task_id, body, actor_kind, actor_id, occurred_at, pinned) VALUES (?, ?, ?, 'user', 'paul', '2027-01-01', ?)");
  seed.exec("BEGIN");
  for (let i = 0; i < 100; i++) insert.run(`comment-${i}`, created.task.id, `Evidence ${i}`, i === 0 ? 1 : 0);
  seed.exec("COMMIT");
  const smallStart = performance.now();
  const small = app.queryUserTaskDetail(created.task.id);
  const smallTime = performance.now() - smallStart;
  seed.exec("BEGIN");
  for (let i = 100; i < 10_000; i++) insert.run(`comment-${i}`, created.task.id, `Evidence ${i}`, 0);
  seed.exec("COMMIT");
  const largeStart = performance.now();
  const result = app.queryUserTaskDetail(created.task.id);
  const largeTime = performance.now() - largeStart;
  assert.ok(result.available);
  assert.equal(result.task.comments.length, 50);
  assert.equal(result.task.comments[0]?.id, "comment-9999");
  assert.equal(result.inspection.pinnedComments[0]?.id, "comment-0");
  assert.ok(result.task.activity.length <= 50);
  assert.equal(result.timeline.total, 10_001);
  const older = app.queryTaskTimeline(created.task.id, { cursor: result.timeline.olderCursor! });
  assert.ok(older.available);
  assert.equal(older.page.records[0]?.key, "comment-comment-9949");
  insert.run("arriving", created.task.id, "New live content", 0);
  const next = app.queryTaskTimeline(created.task.id, { cursor: older.page.olderCursor! });
  assert.ok(next.available);
  assert.equal(next.page.records[0]?.key, "comment-comment-9899");
  const refresh = app.queryTaskTimeline(created.task.id);
  assert.ok(refresh.available);
  assert.equal(refresh.page.records[0]?.key, "comment-arriving");
  const direct = app.queryTaskTimeline(created.task.id, { sourceId: "comment-0" });
  assert.ok(direct.available);
  assert.equal(direct.page.records[0]?.key, "comment-comment-0");
  assert.equal(direct.page.start, 10_000);
  t.diagnostic(`Initial projection: 100 comments ${smallTime.toFixed(2)}ms / ${Buffer.byteLength(JSON.stringify(small))} bytes; 10,000 comments ${largeTime.toFixed(2)}ms / ${Buffer.byteLength(JSON.stringify(result))} bytes. Hydrated comments: 50 plus one independent pin; no transcript reads. Indexed logical counts aggregate compact identities.`);
  assert.deepEqual(app.queryTaskTimeline(created.task.id, { cursor: "forged" }), { available: false, reason: "invalid-page" });
  assert.deepEqual(app.queryTaskTimeline(created.task.id, { pageSize: 151 }), { available: false, reason: "invalid-page" });
  const plan = seed.prepare("EXPLAIN QUERY PLAN SELECT * FROM task_timeline_records INDEXED BY task_timeline_position WHERE task_id = ? AND sequence <= ? AND (occurred_at, sequence) < (?, ?) ORDER BY occurred_at DESC, sequence DESC LIMIT 50")
    .all(created.task.id, 20_000, "2027-01-01", 9999);
  t.diagnostic(JSON.stringify(plan));
  assert.doesNotMatch(JSON.stringify(plan), /SCAN task_timeline_records|TEMP B-TREE/);
  const directPlan = seed.prepare("EXPLAIN QUERY PLAN SELECT * FROM task_timeline_records WHERE task_id = ? AND source_id = ? LIMIT 1").all(created.task.id, "comment-0");
  assert.match(JSON.stringify(directPlan), /task_timeline_record_source/);
  seed.prepare("UPDATE tasks SET archived_at = '2027-02-01' WHERE id = ?").run(created.task.id);
  const archived = app.queryUserTaskDetail(created.task.id);
  assert.ok(archived.available && archived.task.archived);
  assert.equal(archived.inspection.pinnedComments[0]?.id, "comment-0");
  assert.ok(app.queryTaskTimeline(created.task.id, { sourceId: "comment-0" }).available);
});

test("one large attempt keeps bounded grouped disclosure and every movement navigates directly", async (t) => {
  const fixture = await createHandoffFixture();
  const app = await CoordinationApplication.start({ processDefinitionPath: fixture.definitionPath, databasePath: fixture.databasePath });
  t.after(() => app.close());
  const created = app.createTask({ boardId: "delivery", columnId: "implementation", title: "Grouped journey", description: "Compact map", actor: { kind: "user", id: "paul" }, idempotencyKey: "journey" });
  assert.ok(created.accepted);
  const activation = created.task.activations[0]!;
  const seed = new DatabaseSync(fixture.databasePath);
  t.after(() => seed.close());
  seed.prepare("INSERT INTO attempts(id, activation_id, status, workspace_path, started_at) VALUES ('large-attempt', ?, 'running', 'fixture', '2027-01-01')").run(activation.id);
  const insert = seed.prepare("INSERT INTO activity_ledger(id, task_id, type, actor_kind, actor_id, occurred_at, details_json) VALUES (?, ?, 'task.moved', 'agent', 'implementer', '2027-01-01', ?)");
  seed.exec("BEGIN");
  for (let i = 0; i < 10_000; i++) insert.run(`move-${i}`, created.task.id, JSON.stringify({ attemptId: "large-attempt", fromColumnId: "backlog", toColumnId: "implementation", fromColumnName: "Historical backlog", toColumnName: "Historical implementation", unrelatedEvidence: "X".repeat(1000) }));
  seed.exec("COMMIT");
  const result = app.queryUserTaskDetail(created.task.id);
  assert.ok(result.available);
  const attempt = result.timeline.records.find((record) => record.kind === "attempt");
  assert.ok(attempt?.kind === "attempt");
  assert.equal(attempt.content.length, 50);
  assert.equal(attempt.contentPage?.total, 10_000);
  const nested = app.queryTaskTimeline(created.task.id, { cursor: attempt.contentPage!.olderCursor! });
  assert.ok(nested.available);
  assert.equal(nested.page.records[0]?.kind === "attempt" && nested.page.records[0].content.length, 50);
  const map = app.queryTaskMovementMap(created.task.id);
  assert.ok(map.available);
  assert.equal(map.map.movements.length, 10_000);
  assert.equal(map.map.movements[0]?.recordId, "attempt-large-attempt");
  assert.equal(map.map.movements[0]?.details.fromColumnName, "Historical backlog");
  assert.equal(map.map.movements[0]?.details.unrelatedEvidence, undefined);
  const direct = app.queryTaskTimeline(created.task.id, { sourceId: "move-0" });
  assert.ok(direct.available);
  const target = direct.page.records[0];
  assert.ok(target?.kind === "attempt");
  assert.equal(target.content.length, 1);
  assert.equal(target.content[0]?.kind === "activity" && target.content[0].activity.id, "move-0");
  assert.deepEqual(app.queryTaskMovementMap(created.task.id, map.map.cursor), { available: true, map: { movements: [], cursor: map.map.cursor, total: 10_000 } });
  seed.prepare("UPDATE attempts SET status = 'completed', completed_at = '2027-01-02', outcome_status = 'completed', outcome_summary = 'Settled' WHERE id = 'large-attempt'").run();
  const settled = app.queryTaskTimeline(created.task.id, { cursor: direct.page.refreshCursor, refresh: true });
  assert.ok(settled.available);
  assert.equal(settled.page.records[0]?.kind === "attempt" && settled.page.records[0].attempt.outcome?.summary, "Settled");
});

test("ten thousand settled activations leave current controls and costs independent of the timeline page", async (t) => {
  const fixture = await createHandoffFixture();
  const app = await CoordinationApplication.start({ processDefinitionPath: fixture.definitionPath, databasePath: fixture.databasePath });
  t.after(() => app.close());
  const created = app.createTask({ boardId: "delivery", columnId: "implementation", title: "Many runs", description: "Bounded controls", actor: { kind: "user", id: "paul" }, idempotencyKey: "runs" });
  assert.ok(created.accepted);
  const first = created.task.activations[0]!;
  const seed = new DatabaseSync(fixture.databasePath);
  t.after(() => seed.close());
  seed.prepare("UPDATE activations SET status = 'completed' WHERE id = ?").run(first.id);
  const activation = seed.prepare("INSERT INTO activations(id, task_id, target_agent_id, reason_type, source_event_id, status, created_at, definition_version, conversation_id) SELECT ?, task_id, target_agent_id, reason_type, source_event_id, 'completed', created_at, definition_version, conversation_id FROM activations WHERE id = ?");
  const attempt = seed.prepare("INSERT INTO attempts(id, activation_id, status, workspace_path, started_at, completed_at) VALUES (?, ?, 'completed', 'fixture', '2027-01-01', '2027-01-02')");
  const cost = seed.prepare("INSERT INTO attempt_transcripts(attempt_id, items_json, usage_json) VALUES (?, '[]', '{\"estimatedCostUsd\":0.01}')");
  seed.exec("BEGIN");
  for (let i = 0; i < 10_000; i++) { activation.run(`activation-${i}`, first.id); attempt.run(`attempt-${i}`, `activation-${i}`); cost.run(`attempt-${i}`); }
  seed.exec("COMMIT");
  // Unloaded invalid evidence is a sentinel: queries must not parse all activity.
  seed.prepare("INSERT INTO activity_ledger(id, task_id, type, actor_kind, actor_id, occurred_at, details_json) VALUES ('unloaded-sentinel', ?, 'relationship.removed', 'user', 'paul', '2020-01-01', 'invalid JSON')").run(created.task.id);
  const result = app.queryUserTaskDetail(created.task.id);
  assert.ok(result.available);
  assert.equal(result.timeline.records.length, 50);
  assert.equal(result.task.activations.length, 1);
  assert.ok(Math.abs(result.conversationCost!.costEstimate!.amount - 100) < 0.000001);
  assert.equal(result.timeline.records[0]?.kind === "attempt" && result.timeline.records[0].number, 1);
  seed.prepare("UPDATE activity_ledger SET details_json = '{}' WHERE id = 'unloaded-sentinel'").run();
  const direct = app.queryTaskTimeline(created.task.id, { sourceId: "attempt-0" });
  assert.ok(direct.available);
  assert.equal(direct.page.records[0]?.kind === "attempt" && direct.page.records[0].attempt.id, "attempt-0");
  const other = app.createTask({ boardId: "delivery", columnId: "implementation", title: "Scope", description: "Cursor scope", actor: { kind: "user", id: "paul" }, idempotencyKey: "scope" });
  assert.ok(other.accepted);
  assert.deepEqual(app.queryTaskTimeline(other.task.id, { cursor: result.timeline.olderCursor! }), { available: false, reason: "invalid-page" });
  assert.deepEqual(app.queryTaskTimeline(other.task.id, { sourceId: "attempt-0" }), { available: false, reason: "not-found" });
});
