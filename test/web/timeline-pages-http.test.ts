import assert from "node:assert/strict";
import test from "node:test";
import { mkdtemp, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { DatabaseSync } from "node:sqlite";
import { CoordinationApplication } from "../../src/application/coordination-application.ts";
import { startWebServer } from "../../src/web/web-server.ts";
import { createHandoffFixture } from "../support/handoff-fixture.ts";
import type { TimelineQueryResult, MovementMapQueryResult } from "../../src/application/timeline-contract.ts";

test("HTTP task history is bounded, directly navigable and map refresh is compact", async (t) => {
  const fixture = await createHandoffFixture();
  const app = await CoordinationApplication.start({ processDefinitionPath: fixture.definitionPath, databasePath: fixture.databasePath });
  t.after(() => app.close());
  const created = app.createTask({ boardId: "delivery", columnId: "implementation", title: "HTTP journey", description: "Bounded", actor: { kind: "user", id: "paul" }, idempotencyKey: "http-journey" });
  assert.ok(created.accepted);
  const seed = new DatabaseSync(fixture.databasePath);
  const insert = seed.prepare("INSERT INTO activity_ledger(id, task_id, type, actor_kind, actor_id, occurred_at, details_json) VALUES (?, ?, 'task.moved', 'user', 'paul', '2027-01-01', '{\"fromColumnId\":\"backlog\",\"toColumnId\":\"implementation\"}')");
  seed.exec("BEGIN");
  for (let i = 0; i < 10_000; i++) insert.run(`http-move-${i}`, created.task.id);
  seed.exec("COMMIT"); seed.close();
  const assets = await mkdtemp(join(tmpdir(), "timeline-assets-"));
  await writeFile(join(assets, "index.html"), "<div></div>");
  const server = await startWebServer(app, { host: "127.0.0.1", port: 0, assetDirectory: assets });
  t.after(() => server.close());
  const endpoint = `${server.baseUrl}/api/tasks/${created.task.id}`;
  const response = await fetch(`${endpoint}/timeline`);
  assert.equal(response.status, 200);
  const result = await response.json() as TimelineQueryResult;
  assert.ok(result.available);
  assert.equal(result.page.records.length, 50);
  const target = await (await fetch(`${endpoint}/timeline?sourceId=http-move-0`)).json() as TimelineQueryResult;
  assert.ok(target.available);
  assert.equal(target.page.records[0]?.key, "activity-http-move-0");
  assert.equal((await fetch(`${endpoint}/timeline?pageSize=151`)).status, 400);
  assert.equal((await fetch(`${endpoint}/timeline?cursor=forged`)).status, 400);
  const map = await (await fetch(`${endpoint}/movement-map`)).json() as MovementMapQueryResult;
  assert.ok(map.available);
  assert.equal(map.map.movements.length, 10_000);
  const delta = await (await fetch(`${endpoint}/movement-map?after=${map.map.cursor}`)).json() as MovementMapQueryResult;
  assert.ok(delta.available);
  assert.equal(delta.map.movements.length, 0);
  assert.equal((await fetch(`${endpoint}/movement-map?after=-1`)).status, 400);
});
