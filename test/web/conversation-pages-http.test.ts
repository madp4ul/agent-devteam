import assert from "node:assert/strict";
import { mkdtemp, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { tmpdir } from "node:os";
import { DatabaseSync } from "node:sqlite";
import test from "node:test";
import { CoordinationApplication } from "../../src/application/coordination-application.ts";
import type { AgentConversationQueryResult } from "../../src/application/conversation-contract.ts";
import { startWebServer } from "../../src/web/web-server.ts";
import { createHandoffFixture } from "../support/handoff-fixture.ts";

test("HTTP pages bound a large attempt and validate limits, scopes and direct sources", async (t) => {
  const fixture = await createHandoffFixture();
  const application = await CoordinationApplication.start({ processDefinitionPath: fixture.definitionPath, databasePath: fixture.databasePath });
  t.after(() => application.close());
  const created = application.createTask({ boardId: "delivery", columnId: "implementation", title: "HTTP pages", description: "Large retained evidence", actor: { kind: "user", id: "paul" }, idempotencyKey: "http-pages" });
  assert.ok(created.accepted);
  const activation = created.task.activations[0]!;
  const seed = new DatabaseSync(fixture.databasePath);
  seed.prepare("UPDATE activations SET status = 'completed' WHERE id = ?").run(activation.id);
  seed.prepare("INSERT INTO attempts(id, activation_id, status, workspace_path, started_at, completed_at, thread_id) VALUES ('http-attempt', ?, 'completed', 'fixture', '2026-01-01', '2026-01-02', 'http-thread')").run(activation.id);
  seed.prepare("INSERT INTO attempt_transcripts(attempt_id, items_json) VALUES ('http-attempt', ?)").run(JSON.stringify(Array.from({ length: 10_000 }, (_, index) => ({ id: `http-${index}`, kind: "message", role: "agent", text: `HTTP evidence ${index}` }))));
  seed.close();
  const assets = await mkdtemp(join(tmpdir(), "conversation-http-assets-"));
  await writeFile(join(assets, "index.html"), "<div id='root'></div>");
  const server = await startWebServer(application, { host: "127.0.0.1", port: 0, assetDirectory: assets });
  t.after(() => server.close());
  const endpoint = `${server.baseUrl}/api/tasks/${created.task.id}/conversations/${activation.conversationId}`;
  const latest = await fetch(endpoint);
  assert.equal(latest.status, 200);
  const payload = await latest.json() as AgentConversationQueryResult;
  assert.ok(payload.available);
  assert.equal(payload.conversation.history.length, 50);
  const older = await fetch(`${endpoint}?cursor=${encodeURIComponent(payload.conversation.page!.olderCursor!)}`);
  assert.equal(older.status, 200);
  const previous = await older.json() as AgentConversationQueryResult;
  assert.ok(previous.available);
  assert.equal(previous.conversation.history.length, 50);
  assert.equal(new Set([...previous.conversation.page!.recordIds, ...payload.conversation.page!.recordIds]).size, 100);
  assert.equal((await fetch(`${endpoint}?pageSize=151`)).status, 400);
  assert.equal((await fetch(`${endpoint}?pageSize=NaN`)).status, 400);
  assert.equal((await fetch(`${endpoint}?cursor=forged`)).status, 400);
  const direct = await fetch(`${endpoint}?attemptId=http-attempt`);
  assert.equal(direct.status, 200);
  const target = await direct.json() as AgentConversationQueryResult;
  assert.ok(target.available);
  assert.equal(target.conversation.history[0]?.kind, "activation");
  const other = application.createTask({ boardId: "delivery", columnId: "implementation", title: "Scope", description: "Isolated", actor: { kind: "user", id: "paul" }, idempotencyKey: "http-scope" });
  assert.ok(other.accepted);
  const otherEndpoint = `${server.baseUrl}/api/tasks/${other.task.id}/conversations/${other.task.activations[0]!.conversationId}`;
  assert.equal((await fetch(`${otherEndpoint}?cursor=${encodeURIComponent(payload.conversation.page!.olderCursor!)}`)).status, 400);
  assert.equal((await fetch(`${otherEndpoint}?attemptId=http-attempt`)).status, 400);
});
