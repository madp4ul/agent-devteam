test("authenticated claim rejection returns actionable mixed-cycle evidence without establishing a wait", async t => {
  const directory = await mkdtemp(join(tmpdir(), "resource-cycle-api-"));
  const app = await CoordinationApplication.start({ processDefinitionPath: resolve("examples/software-delivery/process.yaml"), databasePath: join(directory, "state.sqlite") });
  t.after(() => app.close());
  const actor = { kind: "user" as const, id: "user" };
  const tasks = ["Owner", "Requester"].map(title => {
    const result = app.createTask({ boardId: "delivery", columnId: "backlog", title, description: title, actor, idempotencyKey: title });
    assert.ok(result.accepted); return result.task.id;
  });
  const resource = app.createResource({ title: "Native game", actor, idempotencyKey: "game" }); assert.ok(resource.accepted);
  assert.ok(app.claimResource({ taskId: tasks[0]!, resourceId: resource.resource.id, actor: { kind: "agent", id: "implementation-agent" }, idempotencyKey: "hold" }).accepted);
  const relationship = app.createTaskRelationship({ sourceTaskId: tasks[0]!, targetTaskId: tasks[1]!, type: "dependency", resumeAgentId: "implementation-agent", actor, idempotencyKey: "dependency" }); assert.ok(relationship.accepted);
  const before = app.queryTask(tasks[1]!);
  const scopes = new AgentToolScopeRegistry();
  const token = scopes.issue({ taskId: tasks[1]!, agentId: "implementation-agent" });
  const server = await startWebServer(app, { host: "127.0.0.1", port: 0, agentToolScopes: scopes }); t.after(() => server.close());
  const rejected = await fetch(`${server.baseUrl}/agent-api/resources/${resource.resource.id}/claim`, { method: "POST", headers: { authorization: `Bearer ${token}`, "content-type": "application/json" }, body: JSON.stringify({ idempotencyKey: "cycle" }) });
  assert.equal(rejected.status, 409);
  const body = await rejected.json();
  assert.equal(body.reason, "circular-wait");
  for (const value of [...tasks, resource.resource.id, relationship.relationship.id, "Consult the participants", "release resources"]) assert.ok(body.diagnostic.includes(value));
  const client = new Client({ name: "resource-cycle-test", version: "1.0.0" });
  await client.connect(new StdioClientTransport({ command: process.execPath, args: ["--experimental-strip-types", resolve("src/mcp/stdio-server.ts"), "--base-url", server.baseUrl, "--token", token], stderr: "pipe" })); t.after(() => client.close());
  const mcp = await client.callTool({ name: "resource.claim", arguments: { resourceId: resource.resource.id, idempotencyKey: "mcp-cycle" } });
  assert.equal(mcp.isError, true);
  const content = (mcp.content as Array<{ type: string; text?: string }>).find(item => item.type === "text")!.text!;
  assert.deepEqual(JSON.parse(content), body);
  assert.deepEqual(app.queryTask(tasks[1]!), before);
});

test("browser and authenticated agents share the resource catalog and cannot spoof retry scope", async t => {
  const directory = await mkdtemp(join(tmpdir(), "resource-api-"));
  const app = await CoordinationApplication.start({ processDefinitionPath: resolve("examples/software-delivery/process.yaml"), databasePath: join(directory, "state.sqlite") });
  t.after(() => app.close());
  const scopes = new AgentToolScopeRegistry();
  const task = app.createTask({ boardId: "delivery", columnId: "backlog", title: "Catalog setup", description: "Create resources", actor: { kind: "user", id: "user" }, idempotencyKey: "setup" });
  assert.ok(task.accepted);
  const token = scopes.issue({ taskId: task.task.id, agentId: "implementation-agent" });
  const server = await startWebServer(app, { host: "127.0.0.1", port: 0, agentToolScopes: scopes });
  t.after(() => server.close());
  assert.equal((await fetch(`${server.baseUrl}/agent-api/resources`)).status, 401);
  const payload = { title: "Game", description: "One window", idempotencyKey: "create" };
  const create = (body: object) => fetch(`${server.baseUrl}/agent-api/resources`, { method: "POST", headers: { authorization: `Bearer ${token}`, "content-type": "application/json" }, body: JSON.stringify(body) });
  const response = await create(payload);
  assert.equal(response.status, 201);
  const created = await response.json();
  assert.deepEqual(await (await create({ ...payload, actor: { kind: "user", id: "spoof" }, originTaskId: "spoof" })).json(), created);
  const list = await (await fetch(`${server.baseUrl}/api/resources`)).json();
  assert.equal(list.resources[0].id, created.resource.id);
  const edit = await fetch(`${server.baseUrl}/api/resources/${created.resource.id}`, { method: "PATCH", headers: { "content-type": "application/json" }, body: JSON.stringify({ title: "Native game", expectedRevision: 1, idempotencyKey: "edit" }) });
  assert.equal(edit.status, 200);
  const archive = await fetch(`${server.baseUrl}/api/resources/${created.resource.id}/archive`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ expectedRevision: 2, idempotencyKey: "archive" }) });
  assert.equal(archive.status, 200);
  assert.equal((await (await fetch(`${server.baseUrl}/api/resources`)).json()).resources.length, 0);
  assert.equal((await (await fetch(`${server.baseUrl}/api/resources?includeArchived=true`)).json()).resources.length, 1);
  const client = new Client({ name: "resource-catalog-test", version: "1.0.0" });
  await client.connect(new StdioClientTransport({ command: process.execPath,
    args: ["--experimental-strip-types", resolve("src/mcp/stdio-server.ts"), "--base-url", server.baseUrl, "--token", token], stderr: "pipe" }));
  t.after(() => client.close());
  const listedTools = await client.listTools();
  for (const name of ["resource.list", "resource.inspect", "resource.create", "resource.edit", "resource.archive"]) assert.ok(listedTools.tools.some(tool => tool.name === name));
  const result = await client.callTool({ name: "resource.create", arguments: { title: "MCP resource", idempotencyKey: "mcp" } });
  assert.notEqual(result.isError, true);
  const text = (result.content as Array<{ type: string; text?: string }>).find(item => item.type === "text")!.text!;
  const resource = JSON.parse(text).resource;
  assert.equal(resource.id, "R-0002");
  assert.equal(resource.description, "");
  const inspection = await client.callTool({ name: "resource.inspect", arguments: { resourceId: resource.id } });
  assert.notEqual(inspection.isError, true);
  const editResult = await client.callTool({ name: "resource.edit", arguments: { resourceId: resource.id, expectedRevision: 1, description: "MCP edited", idempotencyKey: "mcp-edit" } });
  assert.notEqual(editResult.isError, true);
  const archiveResult = await client.callTool({ name: "resource.archive", arguments: { resourceId: resource.id, expectedRevision: 2, idempotencyKey: "mcp-archive" } });
  assert.notEqual(archiveResult.isError, true);
  const listed = await client.callTool({ name: "resource.list", arguments: {} });
  assert.deepEqual(JSON.parse((listed.content as Array<{ type: string; text?: string }>).find(item => item.type === "text")!.text!), { available: true, resources: [] });

});

test("agent claim tools bind ownership to caller scope and release only that task's claims", async t => {
  const directory = await mkdtemp(join(tmpdir(), "resource-claim-api-"));
  const app = await CoordinationApplication.start({ processDefinitionPath: resolve("examples/software-delivery/process.yaml"), databasePath: join(directory, "state.sqlite") });
  t.after(() => app.close());
  const actor = { kind: "user" as const, id: "user" };
  const tasks = ["Owner", "Waiter"].map(title => {
    const result = app.createTask({ boardId: "delivery", columnId: "backlog", title, description: title, actor, idempotencyKey: title });
    assert.ok(result.accepted); return result.task.id;
  });
  const created = app.createResource({ title: "Native game", actor, idempotencyKey: "game" });
  assert.ok(created.accepted);
  const scopes = new AgentToolScopeRegistry();
  const tokens = tasks.map(taskId => scopes.issue({ taskId, agentId: "implementation-agent" }));
  const server = await startWebServer(app, { host: "127.0.0.1", port: 0, agentToolScopes: scopes });
  t.after(() => server.close());
  const post = (path: string, token: string, body: object) => fetch(`${server.baseUrl}${path}`, { method: "POST", headers: { authorization: `Bearer ${token}`, "content-type": "application/json" }, body: JSON.stringify(body) });
  const claimPath = `/agent-api/resources/${created.resource.id}/claim`;
  const first = await post(claimPath, tokens[0]!, { taskId: tasks[1], actor: { kind: "user", id: "spoof" }, idempotencyKey: "first" });
  assert.equal(first.status, 200);
  const held = await first.json();
  assert.equal(held.claim.taskId, tasks[0]);
  assert.equal(held.claim.requestingAgentId, "implementation-agent");
  assert.equal(held.claim.status, "held");
  assert.equal((await post(`/api/resources/${created.resource.id}/claim`, tokens[0]!, { idempotencyKey: "human" })).status, 404);
  const client = new Client({ name: "resource-claim-test", version: "1.0.0" });
  await client.connect(new StdioClientTransport({ command: process.execPath,
    args: ["--experimental-strip-types", resolve("src/mcp/stdio-server.ts"), "--base-url", server.baseUrl, "--token", tokens[1]!], stderr: "pipe" }));
  t.after(() => client.close());
  const result = await client.callTool({ name: "resource.claim", arguments: { resourceId: created.resource.id, idempotencyKey: "second" } });
  assert.notEqual(result.isError, true);
  const pending = JSON.parse((result.content as Array<{ type: string; text?: string }>).find(item => item.type === "text")!.text!);
  assert.equal(pending.claim.status, "pending");
  const denied = await post(`/agent-api/resource-claims/${held.claim.id}/release`, tokens[1]!, { taskId: tasks[0], idempotencyKey: "cross-release" });
  assert.equal(denied.status, 409);
  assert.equal((await denied.json()).reason, "claim-task-mismatch");
  const released = await post(`/agent-api/resource-claims/${held.claim.id}/release`, tokens[0]!, { idempotencyKey: "release" });
  assert.equal(released.status, 200);
  const inspection = app.queryResource(created.resource.id); assert.ok(inspection.available);
  assert.equal(inspection.resource.owner?.id, pending.claim.id);
  const releaseTool = await client.callTool({ name: "resource.release", arguments: { claimId: pending.claim.id, idempotencyKey: "release-second" } });
  assert.notEqual(releaseTool.isError, true);
  const empty = app.queryResource(created.resource.id); assert.ok(empty.available);
  assert.equal(empty.resource.owner, null);
});
